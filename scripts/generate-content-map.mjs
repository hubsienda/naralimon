import fs from "node:fs";
import path from "node:path";
import matter from "gray-matter";

const roots = {
  es: path.join(process.cwd(), "content", "es", "historias"),
  en: path.join(process.cwd(), "content", "en", "stories"),
};

const groups = new Map();

for (const [locale, directory] of Object.entries(roots)) {
  if (!fs.existsSync(directory)) continue;
  for (const file of fs.readdirSync(directory).filter((name) => name.endsWith(".mdx"))) {
    const { data } = matter(fs.readFileSync(path.join(directory, file), "utf8"));
    if (!data.translationKey || !data.slug) continue;
    const key = String(data.translationKey);
    const group = groups.get(key) ?? {};
    group[locale] = { slug: String(data.slug) };
    groups.set(key, group);
  }
}

const map = {};
for (const group of groups.values()) {
  if (!group.es || !group.en) continue;
  const esPath = `/historias/${group.es.slug}`;
  const enPath = `/en/stories/${group.en.slug}`;
  map[esPath] = enPath;
  map[enPath] = esPath;
}

const target = path.join(process.cwd(), "lib", "content", "translations.generated.ts");
fs.mkdirSync(path.dirname(target), { recursive: true });
const output = `// Generated by scripts/generate-content-map.mjs. Do not edit by hand.\nexport const storyTranslationMap: Record<string, string> = ${JSON.stringify(map, null, 2)};\n`;
fs.writeFileSync(target, output);
console.log(`Generated ${Object.keys(map).length / 2} bilingual story mapping(s).`);
